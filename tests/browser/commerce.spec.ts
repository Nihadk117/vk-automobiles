import { signIn } from "../auth-fixtures";
import { test,expect } from "../auth-fixtures";
import type { APIRequestContext } from "@playwright/test";
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import type { Snapshot } from "../../src/shared/shop";
const origin="http://127.0.0.1:3100";
async function command(request:APIRequestContext,action:string,data:unknown){
  const response=await request.post("/api/shop",{headers:{Origin:origin},data:{requestId:randomUUID(),action,data}});
  expect(response.ok()).toBeTruthy();return response.json();
}
test("purchase, supplier payment, credit sale, customer collection, return and A4 receipt",async({page,request},testInfo)=>{
  const tag=String(Date.now()),partName=`Workflow filter ${tag}`;
  const created=await request.post("/api/parts",{headers:{Origin:origin},data:{name:partName,rack:"FLOW-1",openingQuantity:10,sellingPricePaise:28000}});
  const part=(await created.json()).part;expect(created.status()).toBe(201);
  const supplier=await command(request,"party",{kind:"supplier",name:`Supplier ${tag}`});
  const customer=await command(request,"party",{kind:"customer",name:`Customer ${tag}`});
  await page.goto("/shop/purchases");
  await page.getByRole("combobox",{name:"Supplier",exact:true}).selectOption(String(supplier.partyId));
  await page.getByRole("combobox",{name:"Part",exact:true}).selectOption(String(part.id));
  await page.getByRole("button",{name:"Add line",exact:true}).click();
  await page.getByLabel(`Quantity for ${partName}`).fill("5");await page.getByLabel(`Price for ${partName}`).fill("180");
  await page.getByLabel("Cash paid").fill("400");await page.getByRole("checkbox").check();
  await page.getByRole("button",{name:"Post purchase",exact:true}).click();
  await expect(page.getByRole("region",{name:"Document details"})).toContainText("Remaining: ₹500.00");
  await page.goto("/shop/suppliers");
  await page.getByRole("row").filter({hasText:`Supplier ${tag}`}).getByRole("button",{name:"Account / payment"}).click();
  await page.getByLabel("UPI (₹)",{exact:true}).fill("500");await page.getByRole("button",{name:"Record supplier payment"}).click();
  await expect(page.getByRole("heading",{name:`Supplier ${tag} · ₹0.00 outstanding`})).toBeVisible();
  await page.goto("/shop/sales");await page.getByRole("combobox",{name:"Customer",exact:true}).selectOption(String(customer.partyId));
  await page.getByRole("combobox",{name:"Part",exact:true}).selectOption(String(part.id));await page.getByRole("button",{name:"Add line",exact:true}).click();
  await page.getByLabel(`Quantity for ${partName}`).fill("2");await page.getByLabel("UPI paid").fill("200");
  await page.getByRole("checkbox").check();await page.getByRole("button",{name:"Complete sale",exact:true}).click();
  await expect(page.getByRole("region",{name:"Document details"})).toContainText("Remaining: ₹360.00");
  const shop=await (await request.get("/api/shop")).json() as Snapshot;
  const sale=shop.documents.find(d=>d.kind==="sale"&&d.partyId===customer.partyId)!;
  await page.emulateMedia({media:"print"});
  await expect(page.getByRole("region",{name:"Document details"})).toBeVisible();
  await expect(page.getByRole("heading",{name:"Billing & sales",exact:true})).toBeHidden();
  await page.pdf({path:testInfo.outputPath("sample-receipt.pdf"),format:"A4",printBackground:true});
  await page.emulateMedia({media:"screen"});
  await page.goto("/shop/customers");await page.getByRole("row").filter({hasText:`Customer ${tag}`}).getByRole("button",{name:"Account / payment"}).click();
  await page.getByLabel("Cash (₹)",{exact:true}).fill("100");await page.getByRole("button",{name:"Record collection"}).click();
  await expect(page.getByRole("heading",{name:`Customer ${tag} · ₹260.00 outstanding`})).toBeVisible();
  await page.goto("/shop/returns");await page.getByLabel("Original bill").selectOption(String(sale.id));
  await page.getByLabel(`Return quantity for ${partName}`).fill("1");await page.getByLabel("Reason",{exact:true}).fill("Wrong vehicle fitment");
  await page.getByLabel("Cash refund").fill("20");await page.getByRole("checkbox").check();
  await page.getByRole("button",{name:"Record return",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Saved successfully");
  const final=await (await request.get("/api/shop")).json() as Snapshot;
  expect(final.parties.find(p=>p.id===customer.partyId)?.balance).toBe(0);
  expect(final.parties.find(p=>p.id===supplier.partyId)?.balance).toBe(0);
  expect(final.returns.find(r=>r.documentId===sale.id)).toMatchObject({total:28000,debtReduction:26000,refundCash:2000});
  const inventory=(await (await request.get("/api/parts")).json()).parts;
  expect(inventory.find((p:{id:number})=>p.id===part.id).quantity).toBe(14);
  await page.goto("/shop/reports");await expect(page.getByRole("heading",{name:"Reports",exact:true})).toBeVisible();
  await expect(page.getByText("Net sales",{exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath("reports-mobile.png"),fullPage:true});
});
test("downloads and restores a real backup through the settings screen",async({page,request},testInfo)=>{
  const create=await request.post("/api/backups",{headers:{Origin:origin}});expect(create.ok()).toBeTruthy();
  const {name}=await create.json();await page.goto("/shop/settings");
  const downloadPromise=page.waitForEvent("download");await page.getByRole("row").filter({hasText:name}).getByRole("link",{name:"Download"}).click();
  const download=await downloadPromise,path=testInfo.outputPath("restore-test.sqlite");await download.saveAs(path);
  const tag=`Restore temporary ${Date.now()}`;
  await command(request,"party",{kind:"customer",name:tag});
  await page.getByLabel("Backup file").setInputFiles({name:"restore.sqlite",mimeType:"application/vnd.sqlite3",buffer:readFileSync(path)});
  await page.getByLabel("Type RESTORE VK AUTOMOBILES").fill("RESTORE VK AUTOMOBILES");
  await page.getByRole("button",{name:"Validate & restore backup"}).click();
  await expect(page).toHaveURL(/\/login/);
  await signIn(request,origin);await signIn(page.request,origin);await page.goto("/shop/settings");
  const final=await (await request.get("/api/shop")).json() as Snapshot;
  expect(final.parties.some(p=>p.name===tag)).toBe(false);
  await expect(page.getByText(/before-restore-/, {exact:false}).first()).toBeVisible();
});
